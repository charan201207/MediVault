import { useSyncExternalStore } from 'react'
import { createSeedState, expiryOptions } from './dashboardData'
import type { DemoShare, DemoState, DemoProfile, DemoRecord, ExpiryOption, RecordInput } from './dashboardData'

// In-memory demo store. Data lives only in this browser tab and resets on refresh.
// Nothing is written to localStorage, sessionStorage, cookies, or URLs.
// To connect Supabase later, replace this file's actions and hook with real queries.

export type DataStatus = 'loading' | 'ready' | 'error'
export type DemoData = DemoState & { status: DataStatus; error: string | null }

export type ShareInput = {
  recipient_email: string
  record_ids: string[]
  can_download: boolean
  purpose: string
  expires_in: ExpiryOption
}

let state: DemoState = createSeedState()
let idCounter = 0
const listeners = new Set<() => void>()

function setState(next: DemoState): void {
  state = next
  listeners.forEach((listener) => listener())
}

function subscribe(listener: () => void): () => void {
  listeners.add(listener)
  return () => {
    listeners.delete(listener)
  }
}

function getSnapshot(): DemoState {
  return state
}

function nextId(prefix: string): string {
  idCounter += 1
  return `demo-${prefix}-${Date.now().toString(36)}-${idCounter}`
}

// Demo reference only. NOT a security token. Real tokens must be generated by a server.
function makeReference(): string {
  const alphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'
  let reference = ''
  do {
    reference = 'DEMO-' + Array.from({ length: 6 }, () => alphabet[Math.floor(Math.random() * alphabet.length)]).join('')
  } while (state.shares.some((share) => share.reference === reference))
  return reference
}

export function getErrorMessage(caught: unknown): string {
  return caught instanceof Error ? caught.message : 'Something went wrong. Please try again.'
}

export function getDemoState(): DemoState {
  return state
}

export function useDemoData(): DemoData {
  const snapshot = useSyncExternalStore(subscribe, getSnapshot)
  // Always 'ready' in the demo. A Supabase version would report 'loading' and 'error'.
  return { ...snapshot, status: 'ready', error: null }
}

export function addRecord(input: RecordInput): DemoRecord {
  const record: DemoRecord = { id: nextId('rec'), ...input }
  setState({ ...state, records: [record, ...state.records] })
  return record
}

export function updateRecord(id: string, input: RecordInput): void {
  if (!state.records.some((record) => record.id === id)) {
    throw new Error('This record no longer exists.')
  }
  setState({ ...state, records: state.records.map((record) => (record.id === id ? { ...record, ...input } : record)) })
}

export function deleteRecord(id: string): void {
  if (!state.records.some((record) => record.id === id)) {
    throw new Error('This record no longer exists.')
  }
  setState({
    ...state,
    records: state.records.filter((record) => record.id !== id),
    shares: state.shares.map((share) => ({ ...share, record_ids: share.record_ids.filter((recordId) => recordId !== id) })),
  })
}

export function createShare(input: ShareInput): DemoShare {
  const validIds = input.record_ids.filter((id) => state.records.some((record) => record.id === id))
  if (validIds.length === 0) throw new Error('None of the selected records exist any more.')
  const option = expiryOptions.find((candidate) => candidate.value === input.expires_in)
  if (!option) throw new Error('Choose a valid expiry.')

  const createdAt = new Date()
  const share: DemoShare = {
    id: nextId('share'),
    reference: makeReference(),
    recipient_email: input.recipient_email.trim(),
    record_ids: validIds,
    can_download: input.can_download,
    purpose: input.purpose.trim(),
    created_at: createdAt.toISOString(),
    expires_at: new Date(createdAt.getTime() + option.duration_ms).toISOString(),
    revoked_at: null,
  }
  setState({ ...state, shares: [share, ...state.shares] })
  return share
}

export function revokeShare(id: string): void {
  const target = state.shares.find((share) => share.id === id)
  if (!target) throw new Error('This share no longer exists.')
  if (target.revoked_at) return
  const revokedAt = new Date().toISOString()
  setState({ ...state, shares: state.shares.map((share) => (share.id === id ? { ...share, revoked_at: revokedAt } : share)) })
}

export function updateProfile(profile: DemoProfile): void {
  setState({ ...state, profile: { ...profile } })
}

export function resetDemoData(): void {
  setState(createSeedState())
}